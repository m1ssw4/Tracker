// Helper to normalize tags for robust matching (handling curly vs straight quotes, casing, whitespace)
export function normalizeTag(tag: string): string {
  return tag
    .trim()
    .toLowerCase()
    .replace(/[‘’]/g, "'")
    .replace(/\s+/g, ' ');
}

// Find class by tag
export function findClassByTag(searchTag: string): TutoringClass | undefined {
  const normSearch = normalizeTag(searchTag);
  return TUTORING_CLASSES.find(c => {
    const normClassTag = normalizeTag(c.tag);
    return normClassTag === normSearch || 
           normClassTag.includes(normSearch) || 
           normSearch.includes(normClassTag);
  });
}
